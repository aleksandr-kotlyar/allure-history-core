def report(folder, summary=True):
    (folder / "widgets").mkdir(parents=True)
    (folder / "data" / "attachments").mkdir(parents=True)
    (folder / "index.html").write_text('<html><a href="data/attachments/log.txt">log</a></html>')
    (folder / "data" / "attachments" / "log.txt").write_text("original attachment")
    (folder / "executor.json").write_text('{"reportUrl":"original"}')
    if summary:
        (folder / "widgets" / "summary.json").write_text(json.dumps({
            "statistic": {"passed": 10, "failed": 1, "total": 11},
            "time": {"duration": 61000},
        }))


def snapshot(root):
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in root.rglob("*") if p.is_file()}


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.hrefs = []

    def handle_starttag(self, tag, attrs):
        self.hrefs.extend(value for name, value in attrs if name == "href" and value)


def test_cli_indexes_qa_tree_without_writing_source_or_generating_reports(tmp_path, monkeypatch):
    root = tmp_path / "existing-tree"
    group = root / "dev" / "qa-python" / "qa-mdsp-latest"
    old = group / "2026-10-25_14-00-00"
    new = group / "2026-10-26_09-40-00"
    report(old)
    report(new)
    # A later download time must not make the older report the latest one.
    os.utime(old, (2_000_000_000, 2_000_000_000))
    history = group / ".history"
    history.mkdir()
    (history / "history.json").write_text('{"preserved":true}')
    (root / "index.html").write_text("original directory index")
    before = snapshot(root)
    output = tmp_path / "preview"
    monkeypatch.setenv(gui.SHOW_INTRO_ENV, "false")
    monkeypatch.setenv(gui.SHOW_FOOTER_ENV, "false")
    monkeypatch.setattr(allure_history.subprocess, "run", lambda *a, **k: pytest.fail("allure generate invoked"))
    monkeypatch.setattr(allure_history, "prune_reports", lambda *a, **k: pytest.fail("retention invoked"))

    assert allure_history.main([
        "index", "--public-dir", str(root), "--output-dir", str(output),
        "--report-base-url", "https://reports.test/base/prefix/", "--public-title", "QA reports",
    ]) == 0

    assert snapshot(root) == before
    html = (output / "dev/qa-python/qa-mdsp-latest/index.html").read_text()
    assert html.index(new.name + "/") < html.index(old.name + "/")
    assert "1 issue" in html and "1m 01s" in html
    assert '<a href="../../../">QA reports</a>' in html
    assert not (output / "dev/qa-python/qa-mdsp-latest/.history").exists()
    assert not (output / "dev/qa-python/qa-mdsp-latest" / new.name).exists()
    alias = output / "dev/qa-python/qa-mdsp-latest/latest/index.html"
    assert f'https://reports.test/base/prefix/dev/qa-python/qa-mdsp-latest/{new.name}/' in alias.read_text()

    for page in output.rglob("*.html"):
        content = page.read_text()
        assert 'class="hero"' not in content
        assert "No server. No database. No external storage." not in content
        assert "Generated by" not in content
        parser = Links()
        parser.feed(content)
        for href in parser.hrefs:
            url = urlsplit(href)
            if url.scheme:
                assert url.netloc == "reports.test"
                target = root / unquote(url.path.removeprefix("/base/prefix/"))
            else:
                target = page.parent / unquote(url.path)
            if target.is_dir() or url.path.endswith("/"):
                target /= "index.html"
            assert target.exists(), (page, href)


@pytest.mark.parametrize("summary", [None, "not json", "[]", '{"statistic":{"passed":"NaN","failed":"Infinity"}}'])
def test_missing_or_corrupt_summary_keeps_report_and_its_boundary(tmp_path, summary):
    root = tmp_path / "tree"
    folder = root / "dev/qa-python/namespace/2026-10-26_09-00-00"
    report(folder, summary=False)
    if summary is not None:
        (folder / gui.SUMMARY_FILENAME).write_text(summary)
    before = snapshot(root)
    gui.index_tree(root)
    for name, data in before.items():
        assert (root / name).read_bytes() == data
    assert not (folder / "data/index.html").exists()
    assert folder.name in (folder.parent / "index.html").read_text()


def test_generic_report_names_and_nested_public_folder_do_not_reset_breadcrumbs(tmp_path):
    root = tmp_path / "arbitrary-root"
    folder = root / "dev/public/nested/feature & space/run-blue"
    report(folder, summary=False)
    (folder / ".modified_at").write_text("2026-10-26T09:00:00Z")
    gui.index_tree(root)
    html = (folder.parent / "index.html").read_text()
    assert '<a href="../../../../">allure-history</a>' in html
    assert 'href="run-blue/"' in html
    assert not (folder / "data/index.html").exists()
    project = (root / "dev/public/nested/index.html").read_text()
    assert 'href="feature%20%26%20space/latest/"' in project


@pytest.mark.parametrize("destination", ["same", "inside", "ancestor"])
def test_preview_rejects_overlapping_source_and_output(tmp_path, destination):
    root = tmp_path / "source"
    root.mkdir()
    output = {"same": root, "inside": root / "preview", "ancestor": tmp_path}[destination]
    assert allure_history.main(["index", "--public-dir", str(root), "--output-dir", str(output),
                               "--report-base-url", "https://reports.test"]) == 1


def test_symlinked_directories_are_not_followed(tmp_path):
    root = tmp_path / "root"
    root.mkdir()
    outside = tmp_path / "outside"
    outside.mkdir()
    (root / "cycle").symlink_to(root, target_is_directory=True)
    (root / "other").symlink_to(outside, target_is_directory=True)
    gui.index_tree(root)
    assert not list(outside.iterdir())


def test_source_root_cannot_be_a_report(tmp_path):
    root = tmp_path / "2026-10-26_09-00-00"
    report(root)
    assert allure_history.main(["index", "--public-dir", str(root),
                               "--output-dir", str(tmp_path / "out"),
                               "--report-base-url", "https://reports.test"]) == 1
