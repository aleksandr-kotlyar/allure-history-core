#!/usr/bin/env bash
set -euo pipefail

image="${1:?Usage: smoke-runtime.sh IMAGE}"
smoke_dir="$(mktemp -d)"
trap 'rm -rf "$smoke_dir"' EXIT
mkdir -p "$smoke_dir/allure-results"
cp tests/fixtures/allure-results/smoke-result.json "$smoke_dir/allure-results/"

docker run --rm --entrypoint sh "$image" -ec '
  test -s /usr/share/licenses/allure-history-core/LICENSE
  allure-history --help >/dev/null
  allure-history-github --help >/dev/null
  allure-history-gitlab --help >/dev/null
  allure-history-s3 --help >/dev/null
  python3 -c "import boto3"
  s5cmd version
'

docker run --rm --user "$(id -u):$(id -g)" \
  -v "$smoke_dir:/work" -w /work \
  -e GITHUB_REPOSITORY=example/fork \
  -e GITHUB_REF_NAME=smoke \
  -e GITHUB_RUN_ID=1 \
  --entrypoint allure-history-github "$image" build-report

report="$smoke_dir/pages-worktree/public/dev/smoke/job_1"
test -s "$report/index.html"
python3 - "$report/widgets/summary.json" <<'PY'
import json
import sys
from pathlib import Path

statistic = json.loads(Path(sys.argv[1]).read_text())["statistic"]
assert statistic["total"] == 1 and statistic["passed"] == 1, statistic
PY

cp "$report/index.html" "$smoke_dir/original-report.html"
docker run --rm --user "$(id -u):$(id -g)" \
  -v "$smoke_dir:/work" -w /work \
  -e ALLURE_HISTORY_SHOW_INTRO=false -e ALLURE_HISTORY_SHOW_FOOTER=false \
  --entrypoint allure-history "$image" index \
    --public-dir pages-worktree/public --output-dir navigation-preview \
    --report-base-url https://reports.example.test/prefix --public-title "Smoke reports"
cmp "$report/index.html" "$smoke_dir/original-report.html"
python3 - "$smoke_dir/navigation-preview" <<'PY'
from pathlib import Path
import sys

root = Path(sys.argv[1])
assert "Smoke reports" in (root / "index.html").read_text()
assert 'class="hero"' not in (root / "index.html").read_text()
assert "Generated by" not in (root / "index.html").read_text()
assert "https://reports.example.test/prefix/dev/smoke/job_1/" in (root / "dev/smoke/latest/index.html").read_text()
assert not (root / "dev/smoke/job_1").exists()
PY
